_TEMPLATE_BY_ID = {template.template_id: template for template in TEMPLATES}


_CYRILLIC_MAP = str.maketrans(
    {
        "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e", "ж": "zh",
        "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o",
        "п": "p", "р": "r", "с": "s", "т": "t", "у": "u", "ф": "f", "х": "h", "ц": "ts",
        "ч": "ch", "ш": "sh", "щ": "sch", "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
    }
)


def project_slug(project_name: str) -> str:
    raw = str(project_name or "").strip().lower().translate(_CYRILLIC_MAP)
    slug = re.sub(r"[^a-z0-9]+", "-", raw).strip("-")
    return slug or "staffedup-project"


def python_package_name(project_name: str) -> str:
    slug = project_slug(project_name).replace("-", "_")
    slug = re.sub(r"[^a-z0-9_]", "_", slug)
    if not slug or slug[0].isdigit():
        slug = f"app_{slug or 'project'}"
    return slug


def get_project_template(template_id: str) -> ProjectTemplate:
    try:
        return _TEMPLATE_BY_ID[str(template_id)]
    except KeyError as exc:
        raise KeyError(f"Unknown Astra project template: {template_id}") from exc


def project_template_choices() -> tuple[tuple[str, str], ...]:
    return tuple((template.template_id, template.label) for template in TEMPLATES)


def _render(text: str, project_name: str) -> str:
    replacements = {
        "{{PROJECT_NAME}}": project_name,
        "{{PROJECT_SLUG}}": project_slug(project_name),
        "{{PYTHON_PACKAGE}}": python_package_name(project_name),
    }
    rendered = str(text)
    for token, value in replacements.items():
        rendered = rendered.replace(token, value)
    return rendered


def _validated_relative_path(raw: str, project_name: str) -> Path:
    rendered = _render(raw, project_name).replace("\\", "/")
    path = Path(rendered)
    if path.is_absolute() or ".." in path.parts or not path.parts:
        raise ValueError(f"Unsafe project template path: {raw}")
    return path


def rendered_template_files(template_id: str, project_name: str) -> dict[Path, str]:
    template = get_project_template(template_id)
    files: dict[Path, str] = {}
    for raw_path, raw_text in template.files:
        path = _validated_relative_path(raw_path, project_name)
        if path in files:
            raise ValueError(f"Duplicate template path: {path}")
        files[path] = _render(raw_text, project_name)
    return files


def staffedup_metadata(template: ProjectTemplate) -> dict[str, object]:
    return {
        "template": template.template_id,
        "templateVersion": TEMPLATE_SCHEMA_VERSION,
        "healthProfile": template.health_profile,
        "requiredTools": list(template.required_tools),
        "recommendedTools": list(template.recommended_tools),
    }


def _initial_project_config(template: ProjectTemplate, project_name: str, astra_version: str) -> dict[str, object]:
    entry = _render(template.entry_file, project_name) if template.entry_file else ""
    commands = {key: _render(template.commands.get(key, ""), project_name) for key in ("run", "build", "test", "install")}
    return {
        "projectName": project_name,
        "version": str(astra_version).replace("Release ", ""),
        "createdAt": _datetime.datetime.now().isoformat(timespec="seconds"),
        "mainFolder": ".",
        "attachedFolders": [],
        "openFiles": [entry] if entry else [],
        "activeFile": entry,
        "defaultLanguage": template.default_language,
        "pythonInterpreter": "",
        "commands": commands,
        "testExplorerLastRun": None,
        "settings": {
            "tabSize": 4,
            "indentSize": 4,
            "insertSpaces": True,
            "uiFontSize": 13,
            "editorFontSize": 12,
            "consoleFontSize": 10,
        },
        "staffedUp": staffedup_metadata(template),
        "astralStudioVersion": astra_version,
    }


def _ensure_target_is_available(target: Path) -> None:
    if not target.exists():
        return
    if not target.is_dir():
        raise FileExistsError(f"Project target exists and is not a directory: {target}")
    try:
        next(target.iterdir())
    except StopIteration:
        return
    raise FileExistsError(f"Project folder is not empty: {target}")


def create_project_from_template(target_dir: Path, project_name: str, template_id: str, astra_version: str) -> ProjectTemplateResult:
    """Create a complete project skeleton without invoking package managers or the network.

    Files are assembled in a sibling staging directory and moved into place only
    after the whole template has been rendered successfully. Existing non-empty
    folders are never overwritten.
    """

    project_name = str(project_name or "").strip()
    if not project_name:
        raise ValueError("Project name must not be empty")
    target = Path(target_dir)
    parent = target.parent
    parent.mkdir(parents=True, exist_ok=True)
    _ensure_target_is_available(target)

    template = get_project_template(template_id)
    files = rendered_template_files(template.template_id, project_name)
    config = _initial_project_config(template, project_name, astra_version)

    staging: Path | None = Path(tempfile.mkdtemp(prefix=".astra-project-", dir=str(parent)))
    try:
        created_rel: list[Path] = []
        for relative, content in files.items():
            destination = staging / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(content, encoding="utf-8", newline="\n")
            created_rel.append(relative)

        config_rel = Path("astral.project.json")
        (staging / config_rel).write_text(json.dumps(config, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
        created_rel.append(config_rel)

        # A pre-existing empty target can be safely replaced. A non-empty target
        # was rejected above and is never touched.
        if target.exists():
            target.rmdir()
        os.replace(staging, target)
        staging = None

        entry_relative = Path(_render(template.entry_file, project_name)) if template.entry_file else None
        entry_path = target / entry_relative if entry_relative else None
        return ProjectTemplateResult(
            template=template,
            project_dir=target,
            config_path=target / config_rel,
            entry_file=entry_path if entry_path and entry_path.is_file() else None,
            created_files=tuple(target / rel for rel in created_rel),
            staffedup_metadata=staffedup_metadata(template),
        )
    finally:
        if staging is not None and staging.exists():
            shutil.rmtree(staging, ignore_errors=True)
