#!/usr/bin/env python3
"""Build a native macOS .app; use --dmg for an additional distributable image."""
from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path
import platform
import re
import shutil
import subprocess
import sys
import tempfile


ROOT = Path(__file__).resolve().parents[1]
APP_NAME = "Astra Studio"
MINIMUM_MACOS = "13.0"


def spec_source(root: Path, arch: str, icon: Path | None = None, identity: str | None = None, minimum_macos: str = MINIMUM_MACOS) -> str:
    """Use absolute resource paths so spaces/Cyrillic and any working dir work."""
    resources = [(str(root / "assets"), "assets"), (str(root / "data"), "data"),
                 (str(root / "update_channel.json"), "."),
                 (str(root / "scripts" / "check_tools.py"), "scripts")]
    return f'''# Generated by scripts/build_macos.py. Do not edit.
a = Analysis(
    [{str(root / "main.py")!r}], pathex=[{str(root)!r}], binaries=[],
    datas={resources!r}, hiddenimports=[], hookspath=[], hooksconfig={{}},
    runtime_hooks=[], excludes=[], noarchive=False, optimize=0,
)
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name={APP_NAME!r},
          debug=False, bootloader_ignore_signals=False, strip=False, upx=False,
          console=False, target_arch={arch!r}, codesign_identity={identity!r})
collect = COLLECT(exe, a.binaries, a.datas, strip=False, upx=False, name={APP_NAME!r})
app = BUNDLE(collect, name={APP_NAME + ".app"!r}, icon={str(icon) if icon else None!r},
             bundle_identifier="org.astra.studio", info_plist={{
                 "CFBundleShortVersionString": "5.0",
                 "CFBundleVersion": "5.0",
                 "LSMinimumSystemVersion": {minimum_macos!r},
                 "NSHighResolutionCapable": True,
             }})
'''


def minimum_from_load_commands(output: str) -> str | None:
    versions = re.findall(r"\bminos\s+(\d+(?:\.\d+)+)", output)
    versions += re.findall(r"cmd LC_VERSION_MIN_MACOSX\s+cmdsize \d+\s+version (\d+(?:\.\d+)+)", output)
    return max(versions, key=lambda value: tuple(int(part) for part in value.split("."))) if versions else None


def deployment_target() -> str:
    # The build host's Python can require a newer OS than Qt's supported floor.
    # Do not mislabel, for example, a Homebrew Python linked for macOS 26.
    otool = shutil.which("otool")
    if not otool:
        raise RuntimeError("otool from Xcode Command Line Tools is required to verify the deployment target")
    binaries = [Path(sys.executable).resolve()]
    pyside = importlib.util.find_spec("PySide6")
    if pyside is None or not pyside.origin:
        raise RuntimeError("Install requirements.txt in the current build environment first")
    binaries.append(Path(pyside.origin).parent / "Qt" / "lib" / "QtCore.framework" / "Versions" / "A" / "QtCore")
    versions = [MINIMUM_MACOS]
    for binary in binaries:
        output = subprocess.run([otool, "-l", str(binary)], check=True, text=True, capture_output=True).stdout
        version = minimum_from_load_commands(output)
        if version is None:
            raise RuntimeError(f"Unable to determine the macOS deployment target of {binary}")
        versions.append(version)
    return max(versions, key=lambda value: tuple(int(part) for part in value.split(".")))


def build_icon(build_dir: Path) -> Path | None:
    source = ROOT / "assets" / "astra.png"
    sips, iconutil = shutil.which("sips"), shutil.which("iconutil")
    if not source.is_file() or not sips or not iconutil:
        return None
    iconset = build_dir / "astra.iconset"
    iconset.mkdir(parents=True, exist_ok=True)
    for size in (16, 32, 128, 256, 512):
        for scale in (1, 2):
            pixels = size * scale
            suffix = "@2x" if scale == 2 else ""
            output = iconset / f"icon_{size}x{size}{suffix}.png"
            subprocess.run([sips, "-z", str(pixels), str(pixels), str(source), "--out", str(output)], check=True, stdout=subprocess.DEVNULL)
    result = build_dir / "astra.icns"
    subprocess.run([iconutil, "-c", "icns", str(iconset), "-o", str(result)], check=True)
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--arch", choices=("arm64", "x86_64", "universal2"), default=platform.machine())
    parser.add_argument("--dmg", action="store_true", help="also create a DMG with an Applications shortcut")
    parser.add_argument("--codesign-identity", help="optional existing Developer ID identity; default is ad-hoc signing")
    args = parser.parse_args(argv)
    if sys.platform != "darwin":
        parser.error("Run this build on macOS with a matching Python/PySide6 architecture.")
    for needed in ("main.py", "assets", "data/python_libraries.json", "update_channel.json"):
        if not (ROOT / needed).exists():
            parser.error(f"Source distribution is incomplete: {needed}")
    build_dir = ROOT / "build" / f"macos-{args.arch}"
    dist_dir = ROOT / "dist" / f"macos-{args.arch}"
    build_dir.mkdir(parents=True, exist_ok=True)
    dist_dir.mkdir(parents=True, exist_ok=True)
    minimum_macos = deployment_target()
    print(f"Bundle requires macOS {minimum_macos}+ (verified Python and Qt load commands)", flush=True)
    icon = build_icon(build_dir)
    spec = build_dir / "astra_macos.spec"
    spec.write_text(spec_source(ROOT, args.arch, icon, args.codesign_identity, minimum_macos), encoding="utf-8")
    subprocess.run([
        sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
        "--distpath", str(dist_dir), "--workpath", str(build_dir / "work"), str(spec),
    ], cwd=ROOT, check=True)
    app = dist_dir / f"{APP_NAME}.app"
    if not (app / "Contents" / "MacOS" / APP_NAME).is_file():
        raise RuntimeError("PyInstaller did not produce the expected app executable")
    subprocess.run(["codesign", "--verify", "--deep", "--strict", str(app)], check=True)
    print(f"Built: {app}")
    if args.dmg:
        if not shutil.which("hdiutil"):
            raise RuntimeError("hdiutil is required for --dmg")
        with tempfile.TemporaryDirectory(prefix="dmg-", dir=build_dir) as temporary:
            staging = Path(temporary)
            shutil.copytree(app, staging / app.name, symlinks=True)
            (staging / "Applications").symlink_to("/Applications")
            image = dist_dir / f"Astra-Studio-5.0-{args.arch}.dmg"
            subprocess.run(["hdiutil", "create", "-volname", APP_NAME, "-srcfolder", str(staging), "-format", "UDZO", "-ov", str(image)], check=True)
            print(f"Built: {image}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
